# Auxiliar functions
def safe_description(val):
    # Ensure the description is a string and escape problematic quotes
    if not isinstance(val, str):
        val = str(val)
    return val.replace('"', "'")

class LangChainMessage(BaseModel):
    role: str
    content: str

