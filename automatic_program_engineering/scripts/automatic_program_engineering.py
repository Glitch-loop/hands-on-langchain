def assess_the_extraction_accuracy(information_extracted: dict, reference_output: dict) -> dict:
    # Compare each field
    comparison = {}

    for key in reference_output:
        ref_val = reference_output[key]
        model_val = information_extracted.get(key, None)
        comparison[key] = {
            "expected": ref_val,
            "actual": model_val,
            "match": ref_val == model_val
        }

    print("\nField-by-field comparison:")
    for k, v in comparison.items():
        print(f"{k}: expected={v['expected']} | actual={v['actual']} | match={v['match']}")

    # Calculate accuracy
    total = len(comparison)
    correct = sum(1 for v in comparison.values() if v["match"])
    accuracy = correct / total if total > 0 else 0.0
    print(f"\nOverall accuracy: {accuracy*100:.2f}%")
    
    comparison['overall_accuracy'] = accuracy

    return comparison

def store_prompt_template(prompt_template_dict: dict, accuracy: dict) -> str:
    prompt_template_dir = "automatic_program_engineering/prompt_template"
    os.makedirs(prompt_template_dir, exist_ok=True)

    # Save template dict and accuracy
    prompt_template_to_store = {
        "prompt_template": prompt_template_dict,
        "accuracy": accuracy
    }

    unique_id = str(uuid.uuid4())
    prompt_template_path = os.path.join(prompt_template_dir, f"prompt_template_{unique_id}.json")
    with open(prompt_template_path, "w", encoding="utf-8") as f:
        json.dump(prompt_template_to_store, f, ensure_ascii=False, indent=2)
    print(f"\nPrompt template and accuracy saved to {prompt_template_path}")

def store_candidate_schema(auto_generated_candidate_schema_pathfile: str, auto_generated_prompt_pathfile: str, assess_candidate_prompt: dict, output_destination: str):
    
    # Get accuracy as percentage string
    accuracy = assess_candidate_prompt.get('accuracy')
    if accuracy is None:
        accuracy = assess_candidate_prompt.get('overall_accuracy', 0.0)
    accuracy_percent = int(round(accuracy * 100))
    # Generate unique folder name
    folder_name = f"{accuracy_percent}%_{uuid.uuid4()}"
    result_folder = os.path.join(output_destination, folder_name)
    os.makedirs(result_folder, exist_ok=True)

    # Copy the candidate schema file
    shutil.copy2(auto_generated_candidate_schema_pathfile, os.path.join(result_folder, os.path.basename(auto_generated_candidate_schema_pathfile)))
    # Copy the prompt file
    shutil.copy2(auto_generated_prompt_pathfile, os.path.join(result_folder, os.path.basename(auto_generated_prompt_pathfile)))

    # Store the assessment dict as JSON
    assessment_path = os.path.join(result_folder, "assessment.json")
    with open(assessment_path, "w", encoding="utf-8") as f:
        json.dump(assess_candidate_prompt, f, ensure_ascii=False, indent=2)
    print(f"Results stored in {result_folder}")


